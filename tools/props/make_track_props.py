def make_texture():
    """One small picture for all props: flat colour squares, the tyre tread and the block pattern."""
    px = np.zeros((SIZE, SIZE, 3), dtype=np.uint8)
    px[:, :] = RUBBER
    for k, colour in enumerate(SWATCHES):
        px[0:32, k * 32:(k + 1) * 32] = colour

    # Tyre tread: chunky blocks above and below, shifted against each other, an orange ring in the middle.
    px[TREAD_TOP:TREAD_BOTTOM, :] = SHADOW
    block, gap = 12, 4                                  # 16 px per block: 16 blocks around the tyre
    for x in range(SIZE):
        if x % (block + gap) < block:
            px[TREAD_TOP + 1:TREAD_TOP + 12, x] = TREAD
        if (x + 8) % (block + gap) < block:
            px[TREAD_BOTTOM - 12:TREAD_BOTTOM - 1, x] = TREAD
    px[TREAD_TOP + 13:TREAD_TOP + 19, :] = ORANGE

    # Block wall: rows of blocks, every second row shifted by half a block, slightly different greys.
    rng = np.random.default_rng(7)                      # fixed seed: the same picture on every run
    rows, per_row = 4, 8
    row_h, block_w = (BRICK_BOTTOM - BRICK_TOP) // rows, SIZE // per_row
    joint = tuple(int(c * 0.55) for c in WALL_GREY)
    for r in range(rows):
        shift = block_w // 2 if r % 2 else 0
        for b in range(per_row + 1):
            x0 = b * block_w - shift
            shade = 1.0 + rng.uniform(-0.12, 0.12)
            colour = tuple(min(255, int(c * shade)) for c in WALL_GREY)
            y0 = BRICK_TOP + r * row_h
            px[y0:y0 + row_h, max(0, x0):max(0, min(SIZE, x0 + block_w))] = colour
            for edge in (x0, x0 + block_w - 1):
                if 0 <= edge < SIZE:
                    px[y0:y0 + row_h, edge] = joint
        px[BRICK_TOP + r * row_h, :] = joint
    px[BRICK_BOTTOM - 1, :] = joint

    os.makedirs(OUT, exist_ok=True)
    image = bpy.data.images.new("TrackProps", SIZE, SIZE, alpha=False)
    rgba = np.ones((SIZE, SIZE, 4), dtype=np.float32)
    rgba[:, :, :3] = px[::-1].astype(np.float32) / 255.0   # Blender starts at the bottom row
    image.pixels.foreach_set(rgba.ravel())
    image.filepath_raw = TEXTURE
    image.file_format = "PNG"
    image.save()
    return image


def swatch(colour):
    """UV of the middle of a flat colour square."""
    k = SWATCHES.index(colour)
    return ((k * 32 + 16) / SIZE, 1.0 - 16 / SIZE)


def row_v(top, bottom, t):
    """V inside a band of the texture: t = 0 at its lower edge, 1 at its upper edge (2 px margin)."""
    low, high = 1.0 - (bottom - 2) / SIZE, 1.0 - (top + 2) / SIZE
    return low + (high - low) * t


