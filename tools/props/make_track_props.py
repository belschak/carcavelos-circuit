"""Track props for Nova Kart (V22w, Luc's playtest of 13 Nov 2026): clean low-poly models of our own.

Luc had five barrier ideas generated by an AI tool (about 10,000 triangles each, 2048 px textures, open edges,
ends that do not tile). They are NOT in the project. This script builds our own versions from plain numbers:
same idea, real size, Boost Orange / Kart White, no text, no logos.

    TyreStack      three kart tyres on top of each other, an orange ring on each tread   (ref w5)
    JerseyBarrier  2 m of water-filled barrier, two 1 m blocks with a slot under each     (ref w2)
    BlockWall      2 m of dark block wall with half a pilaster at each end                (ref w3)
    BlockWallCap   the orange end piece of the block wall                                 (ref w3)
    KerbStrip      2 m of low kerb in orange / white / black blocks with a white rail     (ref w4)

(Ref w1, the white wall with the orange stripe, is built in Unity by NovaKartWall.cs, because it follows the route.)

Run from the project folder:
    /Applications/Blender.app/Contents/MacOS/Blender -b -P tools/props/make_track_props.py
It writes Assets/_Project/Track/Models/<name>.fbx and the shared 256 px texture TrackProps.png, and prints the
triangle count of every model. Afterwards run "Carcavelos Circuit/Set Up Track Props" in Unity (TrackProps.Setup).

Optional pictures, ours next to the references (the references stay where they are, nothing is copied):
    ... -P tools/props/make_track_props.py -- --render <output folder> --refs <folder with w1.glb ... w5.glb>

Every model: length along X, standing on z = 0, centred on the origin, metres. All use one material and one texture.
"""
import math
import os
import sys

import bpy
