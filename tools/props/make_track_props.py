def make_material():
    """The material all props share. Unity replaces it by Track/Materials/TrackProps.mat (TrackProps.Setup), so the
    FBX files only carry its name: the texture is hooked up afterwards, for the pictures, and no file path of this
    computer ends up in the FBX."""
    material = bpy.data.materials.new("TrackProps")
    material.use_nodes = True
    material.node_tree.nodes.get("Principled BSDF").inputs["Roughness"].default_value = 0.7
    return material


def show_texture(material, image):
    nodes = material.node_tree.nodes
    texture = nodes.new("ShaderNodeTexImage")
    texture.image = image
    texture.interpolation = "Closest"
    material.node_tree.links.new(texture.outputs["Color"], nodes.get("Principled BSDF").inputs["Base Color"])


def triangles(obj):
    obj.data.calc_loop_triangles()
    return len(obj.data.loop_triangles)


def open_edges(obj):
    """Edges with only one face. Fine where a hidden face was left out on purpose (under the model, between tyres)."""
    count = {}
    for poly in obj.data.polygons:
        for key in poly.edge_keys:
            count[key] = count.get(key, 0) + 1
    return sum(1 for c in count.values() if c == 1)


def export(obj):
    for other in bpy.context.scene.objects:
        other.select_set(other == obj)
    bpy.context.view_layer.objects.active = obj
    path = os.path.join(OUT, obj.name + ".fbx")
    bpy.ops.export_scene.fbx(filepath=path, use_selection=True, object_types={"MESH"}, apply_unit_scale=True,
                             apply_scale_options="FBX_SCALE_UNITS", axis_forward="-Z", axis_up="Y",
                             bake_space_transform=True, mesh_smooth_type="FACE", use_mesh_modifiers=True,
                             add_leaf_bones=False, bake_anim=False, path_mode="STRIP", embed_textures=False)
    return path


def render_sheet(objects, out_dir, refs_dir):
    """Pictures of our models next to the references, each pair scaled to the same length."""
    os.makedirs(out_dir, exist_ok=True)
    scene = bpy.context.scene
    scene.render.engine = "BLENDER_EEVEE"
    scene.render.resolution_x, scene.render.resolution_y = 1600, 700
    scene.view_settings.view_transform = "Standard"
    world = bpy.data.worlds.new("W")
    world.use_nodes = True
    world.node_tree.nodes["Background"].inputs[0].default_value = (0.22, 0.22, 0.22, 1)
    world.node_tree.nodes["Background"].inputs[1].default_value = 1.0
    scene.world = world
    sun = bpy.data.objects.new("Sun", bpy.data.lights.new("Sun", "SUN"))
    sun.data.energy = 3.0
    sun.rotation_euler = (math.radians(50), 0, math.radians(-35))
    scene.collection.objects.link(sun)
    camera = bpy.data.objects.new("Cam", bpy.data.cameras.new("Cam"))
    scene.collection.objects.link(camera)
    scene.camera = camera
    target = bpy.data.objects.new("Target", None)
    scene.collection.objects.link(target)
    look = camera.constraints.new("TRACK_TO")
    look.target = target
    look.track_axis, look.up_axis = "TRACK_NEGATIVE_Z", "UP_Y"

    pairs = [("TyreStack", "w5"), ("JerseyBarrier", "w2"), ("BlockWall", "w3"), ("KerbStrip", "w4"), ("NovaKartWall", "w1")]
    by_name = {o.name: o for o in objects}
    for o in objects:
        o.hide_render = True
    for ours, ref in pairs:
        shown = []
        length = 2.0
        if ours in by_name:
            obj = by_name[ours]
            obj.hide_render = False
            obj.location = (0, 0, 0)
            shown.append(obj)
            length = max(obj.dimensions)
            if ours == "BlockWall" and "BlockWallCap" in by_name:
                cap = by_name["BlockWallCap"]
                cap.hide_render = False
                cap.location = (-1.0, 0, 0)
                shown.append(cap)
        ref_path = os.path.join(refs_dir or "", ref + ".glb")
        imported = []
        if refs_dir and os.path.exists(ref_path):
            before = set(bpy.data.objects)
            bpy.ops.import_scene.gltf(filepath=ref_path)
            imported = [o for o in bpy.data.objects if o not in before]
            roots = [o for o in imported if o.parent is None]
            meshes = [o for o in imported if o.type == "MESH"]
            bpy.context.view_layer.update()
            pts = np.array([o.matrix_world @ v.co for o in meshes for v in o.data.vertices])
            size = pts.max(0) - pts.min(0)
            turn = math.radians(90) if size[1] > size[0] else 0.0     # some references lie along Y
            scale = (length if ours != "TyreStack" else 0.81 / size[2]) / (max(size[0], size[1]) if ours != "TyreStack" else 1.0)
            for o in roots:
                o.rotation_mode = "XYZ"
                o.rotation_euler[2] += turn
                o.scale = [s * scale for s in o.scale]
                o.location = (0, 1.6 if ours != "TyreStack" else 1.4, 0)
        span = max(length, 1.2)
        camera.location = (span * 0.6, -(span * 1.1 + 1.2), span * 0.45 + 0.9)
        target.location = (0.0, 0.8, 0.35)
        camera.data.lens = 35
        scene.render.filepath = os.path.join(out_dir, "blender_" + ours + "_vs_" + ref + ".png")
        bpy.ops.render.render(write_still=True)
        for o in shown:
            o.hide_render = True
        for o in imported:
            bpy.data.objects.remove(o, do_unlink=True)


def main():
    args = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    render_dir = args[args.index("--render") + 1] if "--render" in args else None
    refs_dir = args[args.index("--refs") + 1] if "--refs" in args else None

    bpy.ops.wm.read_factory_settings(use_empty=True)
    image = make_texture()
    material = make_material()
    objects = [tyre_stack(material), jersey_barrier(material), block_wall(material), block_wall_cap(material),
               kerb_strip(material)]
    bpy.context.view_layer.update()
    for obj in objects:
        path = export(obj)
        d = obj.dimensions
        print("PROP %-14s %4d triangles, %3d open edges, %.2f x %.2f x %.2f m -> %s"
              % (obj.name, triangles(obj), open_edges(obj), d.x, d.y, d.z, os.path.relpath(path, PROJECT)))
    print("PROP texture %d x %d px -> %s" % (SIZE, SIZE, os.path.relpath(TEXTURE, PROJECT)))
    if render_dir:
        show_texture(material, image)
        render_sheet(objects + [nova_kart_wall_sample(material)], render_dir, refs_dir)


main()
