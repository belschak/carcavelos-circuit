HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(PROJECT, "Assets", "_Project", "Track", "Models")
TEXTURE = os.path.join(OUT, "TrackProps.png")
SIZE = 256  # texture is SIZE x SIZE pixels

# Colours (the game's palette: Boost Orange and Kart White are the kerb colours).
WHITE = (0xF4, 0xF4, 0xF0)
ORANGE = (0xFF, 0x8A, 0x1F)
BLACK = (0x1E, 0x1F, 0x21)
WALL_GREY = (0x3D, 0x40, 0x46)
JERSEY = (0xE2, 0xDE, 0xD3)
RUBBER = (0x24, 0x26, 0x29)
SIDEWALL = (0x30, 0x32, 0x36)
SHADOW = (0x12, 0x13, 0x14)
TREAD = (0x4E, 0x51, 0x56)
SWATCHES = [WHITE, ORANGE, BLACK, WALL_GREY, JERSEY, RUBBER, SIDEWALL, SHADOW]  # row of 32 px squares at the top

# Rows of the texture (pixels from the top): what lies where.
TREAD_TOP, TREAD_BOTTOM = 32, 64      # tyre tread with the orange ring, runs once around the whole width
BRICK_TOP, BRICK_BOTTOM = 96, 160     # block pattern of the dark wall, 2 m wide


