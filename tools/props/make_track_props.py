class Builder:
    """Collects faces (corner points + UVs). Corners at the same place are one vertex, so shading is smooth."""

    def __init__(self):
        self.verts, self.index, self.faces, self.uvs = [], {}, [], []

    def _vertex(self, p):
        key = (round(p[0], 5), round(p[1], 5), round(p[2], 5))
        if key not in self.index:
            self.index[key] = len(self.verts)
            self.verts.append(key)
        return self.index[key]

    def face(self, points, uvs, outward):
        """points: 3 or more corners. uvs: one UV for all, or one per corner. outward: rough direction the face
        must look at (decides the winding, so nothing is inside out)."""
        if isinstance(uvs[0], (int, float)):
            uvs = [uvs] * len(points)
        a, b, c = (np.array(points[k], dtype=float) for k in (0, 1, 2))
        normal = np.cross(b - a, c - a)
        if len(points) > 3:
            normal = normal + np.cross(c - a, np.array(points[3], dtype=float) - a)
        if float(np.dot(normal, np.array(outward, dtype=float))) < 0:
            points, uvs = points[::-1], uvs[::-1]
        ids = [self._vertex(p) for p in points]
        if len(set(ids)) < 3:
            return
        self.faces.append(ids)
        self.uvs.append(list(uvs))

    def to_object(self, name, material, sharp_degrees=40.0):
        mesh = bpy.data.meshes.new(name)
        mesh.from_pydata(self.verts, [], self.faces)
        layer = mesh.uv_layers.new(name="UVMap")
        for poly, uvs in zip(mesh.polygons, self.uvs):
            for loop, uv in zip(poly.loop_indices, uvs):
                layer.data[loop].uv = uv
        mesh.materials.append(material)
        mesh.shade_smooth()
        mesh.set_sharp_from_angle(angle=math.radians(sharp_degrees))  # soft where the bend is gentle, crisp elsewhere
        mesh.validate()
        mesh.update()
        obj = bpy.data.objects.new(name, mesh)
        bpy.context.scene.collection.objects.link(obj)
        return obj


def extrude(b, profile, x0, x1, uv, grow0=0.0, grow1=0.0, closed=True, backwards=False):
    """Faces between the same outline at x0 and x1. profile: [(y, z), ...] going round from the right foot (+y) over
    the top to the left foot (backwards=True: the other way round). uv: one UV, or a function
    (segment number, x, corner 0/1 of the segment) -> UV. grow = the outline moved outwards by so much at that end."""
    def at(p, x, grow):
        y, z = p
        return (x, y + (grow if y > 0 else -grow) if abs(y) > 1e-9 else y, z + grow if z > 0.02 else z)

    count = len(profile) if closed else len(profile) - 1
    for s in range(count):
        p, q = profile[s], profile[(s + 1) % len(profile)]
        corners = [at(p, x0, grow0), at(q, x0, grow0), at(q, x1, grow1), at(p, x1, grow1)]
        # Outward = to the right of the way the outline runs (it goes up on the right side and down on the left).
        normal = (q[1] - p[1], -(q[0] - p[0]))
        if backwards:
            normal = (-normal[0], -normal[1])
        if callable(uv):
            uvs = [uv(s, x0, 0), uv(s, x0, 1), uv(s, x1, 1), uv(s, x1, 0)]
        else:
            uvs = uv
        b.face(corners, uvs, (0.0, normal[0], normal[1]))


def end_face(b, profile, x, uv, direction, grow=0.0):
    """Closes an outline that is the same left and right (y -> -y) with flat strips, so it needs no middle point.
    profile must run from the right foot over the top to the left foot."""
    def at(p):
        y, z = p
        return (x, y + (grow if y > 0 else -grow) if abs(y) > 1e-9 else y, z + grow if z > 0.02 else z)

    n = len(profile)
    for s in range(n // 2 - (1 if n % 2 == 0 else 0)):
        a, a2, c2, c = profile[s], profile[s + 1], profile[n - 2 - s], profile[n - 1 - s]
        b.face([at(a), at(a2), at(c2), at(c)], uv(s) if callable(uv) else uv, (direction, 0, 0))


def mirrored(right):
    """A whole outline from its right half (foot to top): right foot, over the top, left foot."""
    return right + [(-y, z) for y, z in reversed(right)]


